"""Write results as JSON (machine-readable) and Markdown (for humans and PRs).

Reports contain aggregate metrics only, never MIND rows, ids or text.
"""

import json
from pathlib import Path
from typing import Any

from firstread_ml.eval.metrics import METRICS

HEADLINE_SLICES = ("overall", "cold_candidates", "cold_users")
PRIMARY = "ndcg@10"
TITLES = {
    "overall": "Overall",
    "cold_candidates": "Cold-start candidates (never clicked in training)",
    "cold_users": "Cold users (history <= 2 clicks)",
}


def best_by(results: dict[str, Any], slice_name: str, models: list[str]) -> tuple[str, float]:
    scored = [(m, results[m][slice_name][PRIMARY]) for m in models if slice_name in results[m]]
    return max(scored, key=lambda x: x[1])


def acceptance(report: dict[str, Any], candidate: str | None, baselines: list[str]) -> list[str]:
    """P1 acceptance: the candidate beats the best baseline on nDCG@10 overall
    and on cold-start candidates. Without a candidate, name the bar to beat."""
    res = report["results"]
    lines = []
    for sl in ("overall", "cold_candidates"):
        b_name, b_val = best_by(res, sl, [b for b in baselines if b in res])
        if candidate and candidate in res:
            c_val = res[candidate][sl][PRIMARY]
            verdict = "PASS" if c_val > b_val else "FAIL"
            lines.append(
                f"ACCEPT {verdict} [{sl}] {candidate} {c_val:.4f} vs best baseline "
                f"{b_name} {b_val:.4f}"
            )
        else:
            lines.append(f"Bar to beat [{sl}]: {b_name} nDCG@10 = {b_val:.4f}")
    return lines


def _table(res: dict[str, Any], slice_name: str) -> list[str]:
    models = [m for m in res if slice_name in res[m]]
    best = {k: max(res[m][slice_name][k] for m in models) for k in METRICS}
    lines = ["| Model | " + " | ".join(m.upper() for m in METRICS) + " |"]
    lines.append("|---|" + "---:|" * len(METRICS))
    for m in models:
        cells = []
        for k in METRICS:
            v = res[m][slice_name][k]
            cells.append(f"**{v:.4f}**" if v == best[k] else f"{v:.4f}")
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    return lines


def to_markdown(report: dict[str, Any], baselines: list[str], candidate: str | None) -> str:
    meta, res, slices = report["meta"], report["results"], report["slices"]
    v, sp = meta["variant"], meta["split"]
    out = [
        f"# Results: MIND-{v}, {sp} split",
        "",
        "Generated by `firstread-ml eval`; do not edit by hand. Aggregates only.",
        "Metrics are per-impression means (AUC, MRR, nDCG@5, nDCG@10); best per column in bold.",
        "Slice and metric definitions: "
        "[ADR 0003](../../docs/adr/0003-mind-data-and-eval-protocol.md).",
        "",
        f"- Test impressions: {meta['test_impressions']:,} "
        f"(excluded, no click or no non-click: {meta['excluded_impressions']:,})",
        f"- Fit impressions: {meta['fit_impressions']:,}",
        f"- Dataset revision: `{meta['dataset_revision']}`; seed {meta['seed']}",
    ]
    if "embedding_cache_id" in meta:
        out.append(f"- Embedding cache id: `{meta['embedding_cache_id']}`")
    out.append("")
    out += [f"> {line}" for line in acceptance(report, candidate, baselines)]
    for sl in HEADLINE_SLICES:
        info = slices[sl]
        extra = (
            f", of which {info['empty_history']:,} with empty history"
            if "empty_history" in info
            else ""
        )
        out += ["", f"## {TITLES[sl]}", "", f"Impressions: {info['n_impressions']:,}{extra}", ""]
        out += _table(res, sl)

    cats = [s for s in slices if s.startswith("category:") and slices[s]["n_impressions"] > 0]
    empty = [s.split(":", 1)[1] for s in slices if s.startswith("category:") and s not in cats]
    models = list(res)
    out += [
        "",
        "## Per category (nDCG@10)",
        "",
        "Candidates restricted to one category. ⚠ = fewer than 100 impressions (low-n).",
        *([f"No qualifying impressions (omitted): {', '.join(empty)}."] if empty else []),
        "",
        "| Category | Impressions | " + " | ".join(models) + " |",
        "|---|---:|" + "---:|" * len(models),
    ]
    for c in cats:
        n = slices[c]["n_impressions"]
        flag = " ⚠" if slices[c]["low_n"] else ""
        vals = [f"{res[m][c][PRIMARY]:.4f}" if c in res[m] else "—" for m in models]
        out.append(f"| {c.split(':', 1)[1]}{flag} | {n:,} | " + " | ".join(vals) + " |")
    return "\n".join(out) + "\n"


def write(
    report: dict[str, Any],
    out_dir: Path,
    baselines: list[str],
    candidate: str | None = None,
) -> tuple[Path, Path]:
    meta = report["meta"]
    stem = f"results-mind-{meta['variant']}-{meta['split']}"
    out_dir.mkdir(parents=True, exist_ok=True)
    j, m = out_dir / f"{stem}.json", out_dir / f"{stem}.md"
    j.write_text(json.dumps(report, indent=1, sort_keys=True) + "\n")
    m.write_text(to_markdown(report, baselines, candidate))
    return j, m
