"""Exploratory data analysis of a MIND variant: aggregates only.

Writes ``ml/reports/eda-mind-<variant>.md`` plus SVG figures. The report holds
counts, distributions and quantiles. It never includes article text, ids or
user ids (MIND may not be redistributed).
"""

from datetime import UTC, datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import polars as pl
from numpy.typing import NDArray

from firstread_ml.mind.data import Impressions
from firstread_ml.mind.load import load_impressions, load_news, prepare
from firstread_ml.mind.manifest import HF_REVISION
from firstread_ml.mind.splits import DAY, clicked_articles, holdout_split
from firstread_ml.paths import mind_raw_dir, processed_dir, reports_dir

matplotlib.rcParams["svg.hashsalt"] = "firstread"  # deterministic SVG ids (clean diffs)

QUANTILES = (0.5, 0.9, 0.99)


def _q(x: NDArray[np.floating] | NDArray[np.integer]) -> str:
    if len(x) == 0:
        return "—"
    qs = np.quantile(x, QUANTILES)
    return f"mean {np.mean(x):.1f} · median {qs[0]:.0f} · p90 {qs[1]:.0f} · p99 {qs[2]:.0f}"


def _days(imps: Impressions) -> str:
    days = np.unique(imps.time // DAY) * DAY
    fmt = [datetime.fromtimestamp(int(d), UTC).strftime("%Y-%m-%d") for d in days]
    counts = np.bincount(np.searchsorted(days, (imps.time // DAY) * DAY))
    return ", ".join(f"{d} ({c:,})" for d, c in zip(fmt, counts, strict=True))


def _hist_svg(values: NDArray[np.integer], title: str, xlabel: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(6, 3.2))
    ax.hist(np.minimum(values, 100), bins=50, color="#4C72B0")
    ax.set_title(title)
    ax.set_xlabel(xlabel + " (capped at 100)")
    ax.set_ylabel("impressions")
    fig.tight_layout()
    fig.savefig(path, format="svg", metadata={"Date": None})
    plt.close(fig)


def _bar_svg(labels: list[str], values: list[float], title: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(6, 0.28 * len(labels) + 1))
    ax.barh(labels[::-1], values[::-1], color="#4C72B0")
    ax.set_title(title)
    ax.set_xlabel("share of articles (%)")
    fig.tight_layout()
    fig.savefig(path, format="svg", metadata={"Date": None})
    plt.close(fig)


def run(variant: str, data_root: Path | None = None, out_dir: Path | None = None) -> Path:
    proc = prepare(
        variant, raw_dir=mind_raw_dir(data_root), out_dir=processed_dir(variant, data_root)
    )
    news = load_news(variant, proc)
    train = load_impressions(variant, "train", proc)
    dev = load_impressions(variant, "dev", proc)
    out_dir = out_dir or reports_dir()
    fig_dir = out_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)

    title_words = news["title"].str.split(" ").list.len().to_numpy()
    abstract_words = news["abstract"].str.split(" ").list.len().to_numpy()
    abstract_words = np.where(news["abstract"].to_numpy() == "", 0, abstract_words)
    cats = (
        news.group_by("category")
        .len()
        .sort(["len", "category"], descending=[True, False])  # name breaks ties: stable output
        .with_columns((pl.col("len") / news.height * 100).alias("pct"))
    )

    clicked_train = clicked_articles(train, news.height)
    dev_cold_occ = float((~clicked_train[dev.cand]).mean() * 100)
    dev_unique = np.unique(dev.cand)
    dev_cold_unique = float((~clicked_train[dev_unique]).mean() * 100)
    fit, hold = holdout_split(train)
    hold_cold = float((~clicked_articles(fit, news.height)[hold.cand]).mean() * 100)

    lines = [
        f"# EDA: MIND-{variant}",
        "",
        "Generated by `firstread-ml eda`; do not edit by hand. Aggregate statistics only.",
        f"Dataset: `Recommenders/MIND` @ `{HF_REVISION[:8]}` (train + dev; test is unused).",
        "",
        "## Size",
        "",
        "| | train | dev |",
        "|---|---:|---:|",
        f"| Impressions | {train.n:,} | {dev.n:,} |",
        f"| Candidate rows | {len(train.cand):,} | {len(dev.cand):,} |",
        f"| Clicks | {int(train.label.sum()):,} | {int(dev.label.sum()):,} |",
        f"| CTR (clicks / candidates) | {train.label.mean() * 100:.2f}% "
        f"| {dev.label.mean() * 100:.2f}% |",
        "",
        f"Articles (union of train and dev `news.tsv`): {news.height:,}.",
        "",
        "## Time range (UTC day, impressions)",
        "",
        f"- train: {_days(train)}",
        f"- dev: {_days(dev)}",
        f"- Tuning holdout = last train day: {hold.n:,} impressions; fit = earlier days: "
        f"{fit.n:,}.",
        "",
        "## Impressions",
        "",
        f"- Candidates per impression: {_q(dev.cand_len)} (dev); {_q(train.cand_len)} (train)",
        f"- Clicks per impression (dev): {_q(np.bincount(dev.cand_imp, weights=dev.label))}",
        f"- History length (dev): {_q(dev.hist_len)}",
        f"- History length (train): {_q(train.hist_len)}",
        f"- Cold users (history ≤ 2): dev {(dev.hist_len <= 2).mean() * 100:.1f}% "
        f"(empty: {(dev.hist_len == 0).mean() * 100:.1f}%); "
        f"train {(train.hist_len <= 2).mean() * 100:.1f}%",
        "",
        "## Cold-start candidates",
        "",
        "Never clicked in training (not a train positive, not in any train history).",
        "",
        f"- Dev candidate rows that are cold: {dev_cold_occ:.1f}%",
        f"- Distinct dev candidates that are cold: {dev_cold_unique:.1f}%",
        f"- Holdout candidate rows that are cold w.r.t. the fit period: {hold_cold:.1f}%",
        "",
        "## Article text (words)",
        "",
        f"- Title: {_q(title_words)}",
        f"- Abstract: {_q(abstract_words)}; empty abstracts: "
        f"{(abstract_words == 0).mean() * 100:.1f}%",
        "",
        "## Categories",
        "",
        "| Category | Articles | Share |",
        "|---|---:|---:|",
    ]
    lines += [f"| {c} | {n:,} | {p:.1f}% |" for c, n, p in cats.iter_rows()]
    lines += [
        "",
        f"![History length](figures/eda-{variant}-history-length.svg)",
        f"![Candidates per impression](figures/eda-{variant}-candidates.svg)",
        f"![Categories](figures/eda-{variant}-categories.svg)",
        "",
    ]
    _hist_svg(
        dev.hist_len,
        f"MIND-{variant} dev: history length",
        "clicks in history",
        fig_dir / f"eda-{variant}-history-length.svg",
    )
    _hist_svg(
        dev.cand_len,
        f"MIND-{variant} dev: candidates per impression",
        "candidates",
        fig_dir / f"eda-{variant}-candidates.svg",
    )
    _bar_svg(
        cats["category"].to_list(),
        cats["pct"].to_list(),
        f"MIND-{variant}: articles per category",
        fig_dir / f"eda-{variant}-categories.svg",
    )
    path = out_dir / f"eda-mind-{variant}.md"
    path.write_text("\n".join(lines))
    return path
