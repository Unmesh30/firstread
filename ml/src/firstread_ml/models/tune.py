"""Tune NRMS-lite on the time-based holdout (never dev).

Trains on train-minus-last-day and evaluates the holdout after every epoch, so
one run gives the whole epoch curve. Each run appends a row per epoch to
``ml/reports/tuning-nrms-lite-<variant>.md`` (aggregates only), which is the
audit trail for the hyperparameters committed in ``ml/configs/nrms_lite.yaml``.
"""

from pathlib import Path
from typing import Any

import numpy as np
import torch
import yaml

from firstread_ml import tracking
from firstread_ml.baselines import FitContext
from firstread_ml.config import NRMSLiteConfig
from firstread_ml.embed_cache import load_or_build
from firstread_ml.eval.harness import load_eval_data
from firstread_ml.eval.metrics import mean_metrics
from firstread_ml.eval.slices import build_slices
from firstread_ml.mind.load import load_news, prepare
from firstread_ml.mind.splits import clicked_articles
from firstread_ml.models.nrms_lite import NRMSLite
from firstread_ml.models.train import resolve_device, train_nrms_lite, user_vectors
from firstread_ml.paths import mind_raw_dir, processed_dir, reports_dir

TRACKED_SLICES = ("overall", "cold_candidates", "cold_users")


def apply_overrides(cfg: NRMSLiteConfig, overrides: list[str]) -> NRMSLiteConfig:
    """``["train.lr=0.0003", "model.heads=4", "seed=1"]`` -> a new validated config."""
    data: dict[str, Any] = cfg.model_dump()
    for item in overrides:
        key, _, value = item.partition("=")
        if key == "seed":
            data["seed"] = yaml.safe_load(value)
            continue
        section, _, field = key.partition(".")
        if not field or section not in ("model", "train"):
            raise ValueError(f"override must look like model.x=1 or train.y=2, got {item!r}")
        data[section][field] = yaml.safe_load(value)  # "3" -> 3; pydantic coerces "1e-3" -> 0.001
    return NRMSLiteConfig.model_validate(data)


def tune(
    variant: str,
    cfg: NRMSLiteConfig,
    label: str,
    data_root: Path | None = None,
    out_dir: Path | None = None,
) -> list[dict[str, Any]]:
    prepare(variant, raw_dir=mind_raw_dir(data_root), out_dir=processed_dir(variant, data_root))
    data = load_eval_data(variant, "holdout", data_root)
    emb = load_or_build(
        variant, load_news(variant, processed_dir(variant, data_root)), None, data_root
    )
    ctx = FitContext(train=data.fit, n_news=data.n_news, first_seen=data.first_seen, emb=emb)
    slices = [
        s
        for s in build_slices(
            data.test, clicked_articles(data.fit, data.n_news), data.category, data.category_names
        )
        if s.name in TRACKED_SLICES
    ]
    device = resolve_device(cfg.train.device)
    table = torch.from_numpy(emb).to(device)
    histories = data.test.histories()

    def on_epoch(epoch: int, model: NRMSLite) -> dict[str, float]:
        users = user_vectors(model, table, histories, device)
        scores = np.einsum("ij,ij->i", users[data.test.cand_imp], emb[data.test.cand])
        out = {}
        for s in slices:
            m = mean_metrics(scores[s.idx], data.test.label[s.idx], s.offsets)
            out[f"{s.name}_ndcg10"] = m["ndcg@10"]
            if s.name == "overall":
                out["overall_auc"] = m["auc"]
        return out

    with tracking.run(f"tune-{variant}-{label}", experiment="firstread-tuning") as run:
        run.params({"label": label} | {f"cfg.{k}": str(v) for k, v in cfg.model_dump().items()})
        _, history = train_nrms_lite(
            cfg, ctx.train, emb, ctx.population_vector, on_epoch=on_epoch, log=run.metrics
        )
    _append_log(variant, label, cfg, history, out_dir or reports_dir())
    return history


def _append_log(
    variant: str, label: str, cfg: NRMSLiteConfig, history: list[dict[str, Any]], out_dir: Path
) -> None:
    path = out_dir / f"tuning-nrms-lite-{variant}.md"
    if not path.exists():
        path.write_text(
            f"# NRMS-lite tuning log: MIND-{variant}, holdout split\n\n"
            "Generated by `firstread-ml tune` (train on fit days, evaluate on train's last day; "
            "dev is never used for tuning). nDCG@10 per epoch. Aggregates only.\n\n"
            "| Run | Config (changes from defaults) | Epoch | Loss | Overall nDCG@10 | Overall AUC "
            "| Cold-cand nDCG@10 | Cold-user nDCG@10 |\n"
            "|---|---|---:|---:|---:|---:|---:|---:|\n"
        )
    defaults = NRMSLiteConfig().model_dump()
    current = cfg.model_dump()
    changes = [
        f"{sec}.{k}={v}"
        for sec in ("model", "train")
        for k, v in current[sec].items()
        if defaults[sec][k] != v and k != "device"
    ] + ([f"seed={cfg.seed}"] if cfg.seed != defaults["seed"] else [])
    rows = [
        f"| {label} | {', '.join(changes) or 'defaults'} | {h['epoch']} | {h['loss']:.4f} "
        f"| {h['overall_ndcg10']:.4f} | {h['overall_auc']:.4f} "
        f"| {h['cold_candidates_ndcg10']:.4f} | {h['cold_users_ndcg10']:.4f} |"
        for h in history
    ]
    with path.open("a") as f:
        f.write("\n".join(rows) + "\n")
